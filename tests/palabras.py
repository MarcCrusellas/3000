"""Palabras page: type chips, Sin empezar, blocks of 100, ranks, all extras, and their switches in Ajustes.
Same setup as e2e.py (site on :8788, `npm run dev` Worker on :8787). Usage: python3 tests/palabras.py [chrome] [shots_dir]"""
import os
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'e2e.py')).read().split('with sync_playwright() as p:')[0]
exec(src)
def shotf(page, name):
    if SHOTS: page.wait_for_timeout(400); page.screenshot(path=f'{SHOTS}/{name}.png')
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=CHROME)
    ctx, ph, cdp, aid = device(browser)
    ph.goto(SITE); gate(ph, 'new'); ph.click('#gateCreate'); in_app(ph); synced(ph)
    ph.evaluate("location.hash = '#words'"); ph.wait_for_timeout(500)
    ph.click('#next10'); ph.wait_for_timeout(300)
    check(ph.evaluate("S.sel.length") == 10, '+10 with no type adds the next 10')
    check(ph.evaluate("document.querySelectorAll('#tSeg button').length") == 5, '5 type chips')
    check(ph.evaluate("document.querySelector('#cAll').textContent") == '2000', 'Todas shows 2000')
    check(ph.evaluate("document.querySelectorAll('#list .bh').length") >= 1 and ph.evaluate("document.querySelector('#list .bh').textContent").startswith('1–100'), 'block header 1–100')
    check(ph.evaluate("document.querySelector('#list .wr .rk').textContent") == '1', 'rank on rows')
    shotf(ph, '1-todas')
    ph.click('#tSeg button[data-t="v"]'); ph.wait_for_timeout(300)
    check(ph.evaluate("[...document.querySelectorAll('#list .wr')].every(r => WBY.get(r.dataset.k).t === 'v')"), 'Verbos chip shows only verbs')
    check(ph.evaluate("document.querySelector('#cAll').textContent") == '470', 'tab counts follow the type (470 verbs)')
    ph.click('#next10'); ph.wait_for_timeout(300)
    check(ph.evaluate("S.sel.slice(10).every(k => WBY.get(k).t === 'v') && S.sel.length === 20"), '+10 with Verbos adds 10 verbs')
    shotf(ph, '2-verbos')
    ph.click('#fSeg button[data-f="todo"]'); ph.wait_for_timeout(300)
    check(ph.evaluate("[...document.querySelectorAll('#list .wr')].every(r => !SEL.has(r.dataset.k) && !S.known[r.dataset.k])"), 'Sin empezar shows only words not added')
    ph.click('#tSeg button[data-t="v"]'); ph.wait_for_timeout(200)
    check(ph.evaluate("W.t") == '', 'tapping the chip again clears it')
    ph.click('#list .bh'); ph.wait_for_timeout(300)
    check(ph.evaluate("!document.getElementById('bjump').hidden && document.querySelectorAll('#bjump button').length === 20"), 'block picker lists 20 blocks')
    shotf(ph, '3-picker')
    ph.click('#bjump button[data-jb="14"]'); ph.wait_for_timeout(600)
    top = ph.evaluate("(() => { const h = document.querySelector('#list .bh[data-b=\"14\"]'); return h && Math.round(h.getBoundingClientRect().top); })()")
    check(top is not None and 0 <= top < 80, 'jump scrolls to 1401–1500 (%s)' % top)
    shotf(ph, '4-jumped')
    ph.evaluate("window.scrollTo(0,0)"); ph.click('#fSeg button[data-f="x"]'); ph.wait_for_timeout(300)
    check(ph.evaluate("document.querySelector('#list .xall').textContent") == 'Ver las 405', 'Otras offers all 405')
    ph.click('#list .xall'); ph.wait_for_timeout(300)
    check(ph.evaluate("document.querySelectorAll('#list .wr').length") == 405, 'all extras listed')
    ph.click('#tSeg button[data-t="a"]'); ph.wait_for_timeout(300)
    check(ph.evaluate("[...document.querySelectorAll('#list .wr')].every(r => DATA.ex[r.dataset.x].t === 'a')"), 'type chips filter extras too')
    shotf(ph, '5-otras')
    ph.click('#list .wr'); ph.wait_for_timeout(500); ph.click('[data-act="lkwant"]'); ph.wait_for_timeout(300)
    check(ph.evaluate("Object.values(S.extra).some(x => x.s === 'want')"), 'saving an extra from the full list works')
    ph.evaluate("sheet(false)"); ph.wait_for_timeout(400)
    # settings: switch everything off
    ph.evaluate("openSettings('words')"); ph.wait_for_timeout(500); shotf(ph, '6-settings')
    for k in ['wt', 'wb', 'wn', 'wp', 'wx']: ph.click('#%sTog' % k); ph.wait_for_timeout(150)
    check(ph.evaluate("['wt','wb','wn','wp','wx'].every(k => S.set[k] === false)"), 'toggles switch the options off')
    ph.evaluate("sheet(false)"); ph.wait_for_timeout(400)
    check(ph.evaluate("document.getElementById('tSeg').hidden && document.getElementById('fTodo').hidden && W.f === 'x' && !document.querySelector('#list .xall')"), 'chips, Sin empezar and Ver todas hidden')
    ph.click('#fSeg button[data-f="all"]'); ph.wait_for_timeout(300)
    check(ph.evaluate("!document.querySelector('#list .bh') && !document.querySelector('#list .rk')"), 'no blocks or ranks when off')
    shotf(ph, '7-off')
    ph.click('#next10'); ph.wait_for_timeout(300)
    check(ph.evaluate("S.sel.length === 30"), '+10 works with the options off')
    print(ok, 'checks passed')
